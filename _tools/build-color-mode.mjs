import {readFile,writeFile} from 'node:fs/promises';
import {lightStyles} from './color-mode-css.mjs';
const root=new URL('../',import.meta.url);
const sources=[['assets/css/style.scss','style'],['assets/css/experience.css','experience'],['assets/css/garrett-guide.css','garrett-guide']];
let css='/* Generated by _tools/build-color-mode.mjs from the existing dark styles. */\n';
for(const [file,key] of sources){
 let source=await readFile(new URL(file,root),'utf8');
 if(key==='style')for(const name of ['digital-storm','removal-ad'])source=source.replace('@import "'+name+'";',await readFile(new URL('_sass/_'+name+'.scss',root),'utf8'));
 css+=lightStyles(source,key);
}
css+=await readFile(new URL('assets/css/color-mode-base.css',root),'utf8');
await writeFile(new URL('assets/css/color-mode.css',root),css);
console.log('Built the monochrome light palette.');
